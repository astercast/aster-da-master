/* Codex network explorer (wave 26) — the 16 word families as an interactive
   network: families as nodes, shared collaborators/producers as edges,
   BFS degrees of separation from Aster, and the connect-the-dots
   shortest-path finder.
   Data: data/v1/codex-network.json (generated by scripts/build_codex_network.py
   — the only source of truth; this file renders, never computes the graph
   itself, except the client-side BFS for the pathfinder, which mirrors the
   payload's own shortest-path structure).

   Views: "Family overlap" (16 family nodes, shared-figure edges) and
   "Voices" (families + figures, family-figure / co-credit / aster edges).
   Interactions: click or Enter/Space a node for its panel, arrow keys move
   focus between nodes in the current view, Esc resets, name search dims
   non-matches. The tables below the graph carry the same data.
   Reduced motion: static layout, no transitions beyond the gated site CSS. */
(function () {
  "use strict";
  var esc = ADM.esc, fmt = ADM.fmt, loadData = ADM.loadData;
  ADM.reveal();

  var svg = document.getElementById("cx-svg");
  var panel = document.getElementById("cx-panel");
  var insightsEl = document.getElementById("cx-insights");
  var degreesBody = document.getElementById("cx-degrees-body");
  var overlapBody = document.getElementById("cx-overlap-body");
  var searchInput = document.getElementById("cx-search");
  var NS = "http://www.w3.org/2000/svg";

  function el(name, attrs, parent) {
    var n = document.createElementNS(NS, name);
    for (var k in attrs) n.setAttribute(k, attrs[k]);
    if (parent) parent.appendChild(n);
    return n;
  }

  function insightCard(k, v, sub) {
    return "<div class=\"nw-stat\"><dt>" + k + "</dt><dd>" + v + "</dd>" +
      "<p>" + sub + "</p></div>";
  }

  function kindWord(kind) {
    return { artist: "Aster da Master", family: "Word family",
      collaborator: "Title-credited collaborator", producer: "Producer",
      both: "Voice + production" }[kind] || kind;
  }

  loadData("data/v1/codex-network.json").then(function (doc) {
    var byId = {};
    doc.nodes.forEach(function (n) { byId[n.id] = n; });
    var famById = {};
    doc.families.forEach(function (f) { famById[f.id] = f; });
    var figById = {};
    doc.figures.forEach(function (f) { figById[f.id] = f; });

    var edgeByPair = {};
    doc.edges.forEach(function (e) {
      edgeByPair[[e.a, e.b].sort().join("|")] = e;
    });
    function edgeBetween(a, b) {
      return edgeByPair[[a, b].sort().join("|")];
    }

    /* adjacency for the client-side pathfinder (mirrors the payload graph) */
    var adj = {};
    doc.nodes.forEach(function (n) { adj[n.id] = []; });
    doc.edges.forEach(function (e) {
      adj[e.a].push(e.b);
      adj[e.b].push(e.a);
    });
    function shortestPath(start, goal, forbidAster) {
      if (start === goal) return [start];
      var prev = {}, q = [start];
      prev[start] = null;
      while (q.length) {
        var u = q.shift();
        var nbs = adj[u] || [];
        for (var i = 0; i < nbs.length; i++) {
          var v = nbs[i];
          if (forbidAster && v === "aster" && v !== goal) continue;
          if (!(v in prev)) {
            prev[v] = u;
            if (v === goal) {
              var path = [v];
              while (prev[path[path.length - 1]] !== null) {
                path.push(prev[path[path.length - 1]]);
              }
              return path.reverse();
            }
            q.push(v);
          }
        }
      }
      return null;
    }

    /* ---------------- insights ---------------- */
    var ins = doc.insights;
    var maxFam = Math.max.apply(null, doc.figures.map(function (f) { return f.family_count; }));
    var tied = doc.figures.filter(function (f) { return f.family_count === maxFam; })
      .map(function (f) { return f.name; });
    insightsEl.innerHTML =
      insightCard("Nodes", fmt(ins.node_count),
        "16 families · " + ins.figure_count + " figures · Aster") +
      insightCard("Most connected family", esc(ins.most_connected_family.name),
        "×" + ins.most_connected_family.figure_count + " voices") +
      insightCard("Most connected figure", esc(ins.most_connected_figure.name),
        "×" + ins.most_connected_figure.family_count + " families" +
        (tied.length > 1 ? " (tied: " + esc(tied.filter(function (t) { return t !== ins.most_connected_figure.name; }).join(", ")) + ")" : "")) +
      insightCard("Largest bridge",
        ins.largest_bridge ? esc(ins.largest_bridge.a_name) + " ↔ " + esc(ins.largest_bridge.b_name) : "—",
        ins.largest_bridge ? "×" + ins.largest_bridge.weight + " shared voices" : "") +
      insightCard("Isolated families", String(ins.isolated_families.length),
        ins.isolated_families.map(function (s) {
          var f = doc.families.filter(function (x) { return x.slug === s; })[0];
          return esc(f ? f.name : s);
        }).join(" · ") || "none");

    /* ---------------- graph ---------------- */
    var gEdges = el("g", { "class": "cx-edges" }, svg);
    var gNodes = el("g", { "class": "cx-nodes" }, svg);
    var recById = {};
    var nodeOrder = []; // focus order for the current view

    function nodeAria(n) {
      return n.name + ", " + kindWord(n.kind) + ". " + n.blurb +
        ". Press Enter to inspect.";
    }

    function shapeFor(n, g) {
      var r = n.r, shape;
      if (n.kind === "producer") {
        shape = el("rect", { x: (n.x - r).toFixed(1), y: (n.y - r).toFixed(1),
          width: (r * 2).toFixed(1), height: (r * 2).toFixed(1),
          rx: "3", "class": "nw-shape" }, g);
      } else if (n.kind === "both") {
        shape = el("path", {
          d: "M " + n.x.toFixed(1) + " " + (n.y - r).toFixed(1) +
             " L " + (n.x + r).toFixed(1) + " " + n.y.toFixed(1) +
             " L " + n.x.toFixed(1) + " " + (n.y + r).toFixed(1) +
             " L " + (n.x - r).toFixed(1) + " " + n.y.toFixed(1) + " Z",
          "class": "nw-shape" }, g);
      } else {
        shape = el("circle", { cx: n.x, cy: n.y, r: r, "class": "nw-shape" }, g);
      }
      return shape;
    }

    doc.nodes.forEach(function (n) {
      var g = el("g", { "class": "nw-node is-" + n.kind, tabindex: "0",
        role: "button", "aria-pressed": "false", "data-id": n.id,
        "aria-label": nodeAria(n) }, gNodes);
      var shape = shapeFor(n, g);
      var labelCls = n.kind === "family" || n.kind === "artist" ? "nw-label" : "nw-label fig-label";
      var t = el("text", { x: n.x, y: (n.y + n.r + 15).toFixed(1),
        "class": labelCls, "text-anchor": "middle", "aria-hidden": "true" }, g);
      t.textContent = n.name;
      if (n.kind === "artist") {
        var at = el("text", { x: n.x, y: (n.y + 8).toFixed(1),
          "class": "nw-artist-label", "text-anchor": "middle",
          "aria-hidden": "true" }, g);
        at.textContent = "A✦";
        var al = el("text", { x: n.x, y: (n.y + n.r + 15).toFixed(1),
          "class": "nw-label", "text-anchor": "middle",
          "aria-hidden": "true" }, g);
        al.textContent = "Aster";
      }
      var rec = { n: n, g: g, shape: shape };
      recById[n.id] = rec;
      g.addEventListener("click", function () { selectNode(n.id); });
      g.addEventListener("keydown", function (ev) { nodeKey(ev, n.id); });
    });

    var style = document.createElementNS(NS, "style");
    style.textContent = ".fig-label{opacity:0;transition:opacity .15s}" +
      ".nw-node:hover .fig-label,.nw-node:focus-visible .fig-label," +
      ".nw-node.is-selected .fig-label{opacity:1}" +
      "@media (prefers-reduced-motion: reduce){.fig-label{transition:none}}";
    svg.appendChild(style);

    var currentView = "overlap";
    var selectedId = null;

    function visibleNodes() {
      if (currentView === "overlap") {
        return doc.nodes.filter(function (n) { return n.kind === "family"; });
      }
      return doc.nodes.slice();
    }

    function visibleEdges() {
      if (currentView === "overlap") {
        return doc.family_overlap.map(function (o) {
          return { a: o.a_id, b: o.b_id, weight: o.weight,
            cls: "is-overlap", label: o.weight + " shared voices: " +
              o.shared_figures.map(function (s) { return s.name; }).join(", ") };
        });
      }
      return doc.edges.map(function (e) {
        var cls = e.kind === "co-credit" ? "is-cocredit"
          : e.kind === "aster-family" ? "is-aster" : "";
        return { a: e.a, b: e.b, weight: e.weight, cls: cls, label: e.label };
      });
    }

    function render() {
      while (gEdges.firstChild) gEdges.removeChild(gEdges.firstChild);
      var vis = {};
      visibleNodes().forEach(function (n) {
        vis[n.id] = true;
        recById[n.id].g.style.display = "";
      });
      doc.nodes.forEach(function (n) {
        if (!vis[n.id]) recById[n.id].g.style.display = "none";
      });
      nodeOrder = visibleNodes().map(function (n) { return n.id; });
      visibleEdges().forEach(function (e) {
        var a = byId[e.a], b = byId[e.b];
        el("line", { x1: a.x, y1: a.y, x2: b.x, y2: b.y,
          "class": "nw-edge " + e.cls,
          "stroke-width": (1 + Math.min(e.weight, 5) * 0.9).toFixed(1) },
          gEdges).appendChild(document.createElementNS(NS, "title")).textContent = e.label;
      });
      applySearch();
      if (selectedId && !vis[selectedId]) clearSelection();
    }

    function nodeKey(ev, id) {
      var idx = nodeOrder.indexOf(id);
      if (ev.key === "Enter" || ev.key === " ") {
        ev.preventDefault(); selectNode(id);
      } else if (ev.key === "ArrowRight" || ev.key === "ArrowDown") {
        ev.preventDefault();
        var nx = nodeOrder[(idx + 1) % nodeOrder.length];
        recById[nx].g.focus();
      } else if (ev.key === "ArrowLeft" || ev.key === "ArrowUp") {
        ev.preventDefault();
        var pv = nodeOrder[(idx - 1 + nodeOrder.length) % nodeOrder.length];
        recById[pv].g.focus();
      } else if (ev.key === "Home") {
        ev.preventDefault(); recById[nodeOrder[0]].g.focus();
      } else if (ev.key === "End") {
        ev.preventDefault(); recById[nodeOrder[nodeOrder.length - 1]].g.focus();
      } else if (ev.key === "Escape") {
        clearSelection();
      }
    }

    function clearSelection() {
      selectedId = null;
      Object.keys(recById).forEach(function (id) {
        recById[id].g.classList.remove("is-selected");
        recById[id].g.setAttribute("aria-pressed", "false");
      });
      panel.innerHTML = "<p class=\"chart-sub\">Select a node to see its connections.</p>";
    }

    function selectNode(id) {
      clearSelection();
      selectedId = id;
      var n = byId[id];
      recById[id].g.classList.add("is-selected");
      recById[id].g.setAttribute("aria-pressed", "true");
      var html = "<h3>" + esc(n.name) + "</h3>" +
        "<p class=\"chart-sub\">" + esc(kindWord(n.kind)) + " · " + esc(n.blurb) + "</p>";
      if (n.kind === "family") {
        var f = famById[id];
        html += "<p class=\"chart-sub\">Words: " + esc(f.words.join(" · ")) + "</p>";
        html += "<p class=\"chart-sub\">Reading: " +
          (f.decoded_status === "unknown"
            ? "the archive assigns no meaning — tallied, never translated"
            : "stated in the codex") + "</p>";
        var pairs = doc.family_overlap.filter(function (o) {
          return o.a_id === id || o.b_id === id;
        });
        if (pairs.length) {
          html += "<h4 class=\"stat-h\">Shares voices with</h4><ul class=\"top-list\">";
          pairs.forEach(function (o) {
            var other = o.a_id === id ? { name: o.b_name, page: o.b_page, slug: o.b_slug }
                                      : { name: o.a_name, page: o.a_page, slug: o.a_slug };
            html += "<li><a href=\"#family-" + esc(other.slug) + "\" data-node=\"fam-" + esc(other.slug) + "\">" +
              esc(other.name) + "</a> — " + o.weight + " shared: " +
              esc(o.shared_figures.map(function (s) { return s.name; }).join(", ")) + "</li>";
          });
          html += "</ul>";
        } else {
          html += "<p class=\"chart-sub\">Shares no voices with any other family — an isolate in the overlap graph.</p>";
        }
        html += "<p><a class=\"nw-link\" href=\"" + esc(n.page) + "\">Open the family deep dive →</a></p>";
      } else if (n.kind !== "artist") {
        var fig = figById[id];
        html += "<h4 class=\"stat-h\">Carried by " + fig.families.length +
          (fig.families.length === 1 ? " family" : " families") + "</h4><ul class=\"top-list\">";
        fig.families.forEach(function (fm) {
          html += "<li><a href=\"#family-" + esc(fm.family_slug) + "\" data-node=\"" + esc(fm.family_id) + "\">" +
            esc(fm.family_name) + "</a> — ×" + fm.transmissions + "</li>";
        });
        html += "</ul>";
        var deg = doc.degrees.filter(function (d) { return d.id === id; })[0];
        html += "<p class=\"chart-sub\">" + deg.degrees + " degrees from Aster, via " +
          deg.via.map(function (vid) { return esc(famById[vid].name); }).join(", ") + ".</p>";
        if (n.page) {
          html += "<p><a class=\"nw-link\" href=\"" + esc(n.page) + "\">" +
            (fig.kind === "producer" && n.page.indexOf("fish-narc") !== -1 ? "Scene figure page" : "Circle page") +
            " →</a></p>";
        } else {
          html += "<p class=\"chart-sub\">No circle page — credited as named, nothing more claimed.</p>";
        }
        if (fig.kind === "producer" || fig.kind === "both") {
          // rotation 22: producer records are folds on producers/index.html;
          // the slug rule mirrors the generator (node id minus the
          // fig-p-/fig- prefix). Every producer/both node is asserted
          // to resolve to a fold.
          var pSlug = id.replace(/^fig-p-/, "").replace(/^fig-/, "");
          html += "<p><a class=\"nw-link\" href=\"producers/index.html#p-" + esc(pSlug) + "\">Producer record →</a></p>";
        }
      } else {
        html += "<p class=\"chart-sub\">0 degrees — the speaker of every family. " +
          "Every family node connects here; every figure is 2 degrees out, via the families that carry them.</p>";
      }
      panel.innerHTML = html;
      panel.querySelectorAll("[data-node]").forEach(function (a) {
        a.addEventListener("click", function (ev) {
          ev.preventDefault();
          var target = a.getAttribute("data-node");
          if (currentView === "overlap" || byId[target].kind === "family") {
            setView("overlap");
          }
          selectNode(target);
          recById[target].g.focus();
        });
      });
    }

    function setView(v) {
      currentView = v;
      var radios = document.querySelectorAll("input[name=\"cx-view\"]");
      for (var i = 0; i < radios.length; i++) radios[i].checked = radios[i].value === v;
      render();
    }
    document.querySelectorAll("input[name=\"cx-view\"]").forEach(function (r) {
      r.addEventListener("change", function () { setView(r.value); });
    });

    /* ---------------- search ---------------- */
    function applySearch() {
      var q = searchInput.value.trim().toLowerCase();
      doc.nodes.forEach(function (n) {
        var rec = recById[n.id];
        var show = rec.g.style.display !== "none";
        rec.g.classList.remove("is-dim");
        if (show && q && n.name.toLowerCase().indexOf(q) === -1 &&
            (n.blurb || "").toLowerCase().indexOf(q) === -1) {
          rec.g.classList.add("is-dim");
        }
      });
    }
    searchInput.addEventListener("input", applySearch);
    searchInput.addEventListener("keydown", function (ev) {
      if (ev.key === "Escape") { searchInput.value = ""; applySearch(); }
      if (ev.key === "Enter") {
        ev.preventDefault();
        var q = searchInput.value.trim().toLowerCase();
        var hit = visibleNodes().filter(function (n) {
          return n.name.toLowerCase().indexOf(q) !== -1;
        })[0];
        if (hit) { selectNode(hit.id); recById[hit.id].g.focus(); }
      }
    });
    document.addEventListener("keydown", function (ev) {
      if (ev.key === "Escape" && document.activeElement !== searchInput) clearSelection();
    });

    /* ---------------- pathfinder ---------------- */
    var fromSel = document.getElementById("cx-from");
    var toSel = document.getElementById("cx-to");
    var pathResult = document.getElementById("cx-path-result");

    function optGroups(sel) {
      function group(label, nodes) {
        var og = document.createElement("optgroup");
        og.label = label;
        nodes.forEach(function (n) {
          var o = document.createElement("option");
          o.value = n.id; o.textContent = n.name;
          og.appendChild(o);
        });
        sel.appendChild(og);
      }
      group("Aster", [byId.aster]);
      group("Families", doc.nodes.filter(function (n) { return n.kind === "family"; })
        .sort(function (a, b) { return a.name < b.name ? -1 : 1; }));
      group("Figures", doc.nodes.filter(function (n) {
        return n.kind !== "family" && n.kind !== "artist";
      }).sort(function (a, b) { return a.name < b.name ? -1 : 1; }));
    }
    optGroups(fromSel);
    optGroups(toSel);
    fromSel.value = "fig-jax";
    toSel.value = "fig-p-runawway";

    function nodeChip(id) {
      var n = byId[id];
      var inner = esc(n.name);
      if (n.page) {
        inner = "<a href=\"" + esc(n.page) + "\">" + inner + "</a>";
      } else if (n.kind === "producer" || n.kind === "both") {
        // rotation 22: producer record fold (slug rule mirrors the generator)
        var pSlug = id.replace(/^fig-p-/, "").replace(/^fig-/, "");
        inner = "<a href=\"producers/index.html#p-" + esc(pSlug) + "\">" + inner + "</a>";
      }
      return inner + " <span class=\"chart-sub\">(" + esc(kindWord(n.kind)) + ")</span>";
    }

    function runPath(a, b, mode, writeHash) {
      var forbidAster = mode === "codex";
      if (forbidAster && (a === "aster" || b === "aster") && a !== b) {
        pathResult.innerHTML = "<p class=\"chart-sub\" role=\"status\">No path found in codex-only mode: " +
          "the Aster shortcut is forbidden and Aster connects to nothing else without it.</p>";
        return;
      }
      var path = shortestPath(a, b, forbidAster);
      if (!path) {
        pathResult.innerHTML = "<p class=\"chart-sub\" role=\"status\">No path found in codex-only mode — " +
          esc(byId[a].name) + " and " + esc(byId[b].name) +
          " share no family and no chain of shared voices connects them. The archive reports the gap; it doesn't fill it.</p>";
      } else {
        var items = path.map(function (id, i) {
          var why = "";
          if (i > 0) {
            var e = edgeBetween(path[i - 1], id);
            why = "<span class=\"step-why\">" + esc(e ? e.label : "") + "</span>";
          }
          return "<li><span class=\"step-n\" aria-hidden=\"true\">" + (i + 1) + "</span>" +
            nodeChip(id) + why + "</li>";
        }).join("");
        var link = "#path=" + a + "," + b + (mode === "codex" ? ",codex" : "");
        pathResult.innerHTML =
          "<p class=\"chart-sub\" role=\"status\">Shortest path: " + (path.length - 1) +
          (path.length === 2 ? " step" : " steps") +
          (forbidAster ? " (codex only)" : " (through the archive)") + ".</p>" +
          "<ol class=\"cx-path-steps\">" + items + "</ol>" +
          "<p><a href=\"" + link + "\">Share this path →</a></p>";
        if (writeHash !== false) {
          try { history.replaceState(null, "", link); } catch (err) { /* noop */ }
        }
      }
    }

    document.getElementById("cx-path-form").addEventListener("submit", function (ev) {
      ev.preventDefault();
      var mode = document.querySelector("input[name=\"cx-mode\"]:checked").value;
      runPath(fromSel.value, toSel.value, mode, true);
    });

    /* ---------------- tables ---------------- */
    degreesBody.innerHTML = doc.degrees.map(function (d) {
      var hash = d.kind === "family" ? "#family-" + d.id.slice(4) : "#figure-" + d.id;
      var via = d.via.map(function (vid) {
        return "<a href=\"#family-" + esc(vid.slice(4)) + "\">" + esc(famById[vid].name) + "</a>";
      }).join(", ") || "—";
      return "<tr><th scope=\"row\"><a href=\"" + hash + "\">" + esc(d.name) + "</a></th>" +
        "<td>" + esc(kindWord(d.kind)) + "</td><td>" + d.degrees + "</td><td>" + via + "</td></tr>";
    }).join("");

    overlapBody.innerHTML = doc.family_overlap.map(function (o) {
      var voices = o.shared_figures.map(function (s) {
        var inner = esc(s.name);
        var pg = figById[s.id] && figById[s.id].page;
        if (!pg && figById[s.id] &&
            (figById[s.id].kind === "producer" || figById[s.id].kind === "both")) {
          // rotation 22: producer record fold (slug rule mirrors the generator)
          pg = "producers/index.html#p-" + s.id.replace(/^fig-p-/, "").replace(/^fig-/, "");
        }
        if (pg) inner = "<a href=\"" + esc(pg) + "\">" + inner + "</a>";
        return inner;
      }).join(", ");
      return "<tr><th scope=\"row\"><a href=\"" + esc(o.a_page) + "\">" + esc(o.a_name) + "</a></th>" +
        "<td><a href=\"" + esc(o.b_page) + "\">" + esc(o.b_name) + "</a></td>" +
        "<td>×" + o.weight + "</td><td>" + voices + "</td></tr>";
    }).join("");

    /* ---------------- deep links ---------------- */
    render();
    var hash = location.hash;
    var m;
    if ((m = /^#family-([a-z0-9-]+)$/.exec(hash))) {
      var fid = "fam-" + m[1];
      if (byId[fid]) { setView("overlap"); selectNode(fid); }
    } else if ((m = /^#figure-([a-z0-9-]+)$/.exec(hash))) {
      if (byId[m[1]]) { setView("voices"); selectNode(m[1]); }
    } else if ((m = /^#path=([^,]+),([^,]+)(,codex)?$/.exec(hash))) {
      var pa = decodeURIComponent(m[1]), pb = decodeURIComponent(m[2]);
      if (byId[pa] && byId[pb]) {
        fromSel.value = pa; toSel.value = pb;
        var radios = document.querySelectorAll("input[name=\"cx-mode\"]");
        for (var i = 0; i < radios.length; i++) {
          radios[i].checked = radios[i].value === (m[3] ? "codex" : "archive");
        }
        runPath(pa, pb, m[3] ? "codex" : "archive", false);
        document.getElementById("cx-path-h").scrollIntoView();
      }
    }
  }).catch(function () {
    panel.innerHTML = "<p class=\"chart-sub\">The graph data failed to load.</p>";
  });
})();
