/* Collaboration network (wave 16) — artist at center, collaborator nodes sized
   by shared tracks, producer nodes as squares, co-credit edges between nodes.
   Data: api/v1/network.json (generated by scripts/build_network.py — the only
   source of truth; this file renders, never computes the graph itself).

   Interactions: drag any node (pointer), click or Enter/Space a node for its
   panel, Arrow keys move focus between nodes, Esc resets. Controls: era
   slider (2018–2026 highlight), producers toggle, name search.
   Accessible core: the table below the graph carries the same data. */
(function () {
  "use strict";
  var esc = ADM.esc, fmt = ADM.fmt, loadData = ADM.loadData;
  ADM.reveal();

  var svg = document.getElementById("nw-svg");
  var panel = document.getElementById("nw-panel");
  var tableWrap = document.getElementById("nw-table-wrap");
  var tableBody = document.getElementById("nw-table-body");
  var insights = document.getElementById("nw-insights");
  var NS = "http://www.w3.org/2000/svg";

  function el(name, attrs, parent) {
    var n = document.createElementNS(NS, name);
    for (var k in attrs) n.setAttribute(k, attrs[k]);
    if (parent) parent.appendChild(n);
    return n;
  }

  function metaLine(t) {
    var bits = [t.date || "date unknown"];
    if (t.plays != null) bits.push(fmt(t.plays) + " plays");
    return bits.join(" · ");
  }

  function insightCard(k, v, sub) {
    return "<div class=\"nw-stat\"><dt>" + k + "</dt><dd>" + v + "</dd>" +
      "<p>" + sub + "</p></div>";
  }

  loadData("api/v1/network.json").then(function (doc) {
    var nodes = doc.nodes;
    var edges = doc.edges;
    var byId = {};
    nodes.forEach(function (n) { byId[n.id] = n; });
    var W = 920, H = 640;
    var gEdges = el("g", { "class": "nw-edges" }, svg);
    var gNodes = el("g", { "class": "nw-nodes" }, svg);
    var recById = {};
    var nodeEls = [];   // focusable nodes, ring order

    /* ---------------- insights bar ---------------- */
    var ins = doc.insights;
    insights.innerHTML =
      insightCard("Most frequent collaborator", esc(ins.most_frequent_collaborator.name),
        "×" + ins.most_frequent_collaborator.track_count + " shared transmissions") +
      insightCard("Producer with most credits",
        ins.producer_most_credits ? esc(ins.producer_most_credits.name) : "—",
        ins.producer_most_credits ? "×" + ins.producer_most_credits.track_count + " produced tracks" : "no producer tracks on record") +
      insightCard("Busiest collab year", String(ins.year_most_collabs.year),
        ins.year_most_collabs.collab_tracks + " credited tracks") +
      insightCard("First-ever collaborator", esc(ins.first_ever_collaborator.name),
        esc(ins.first_ever_collaborator.date) + " · " + esc(ins.first_ever_collaborator.title));

    /* ---------------- edges (under nodes) ---------------- */
    var edgeEls = edges.map(function (e) {
      var a = byId[e.a], b = byId[e.b];
      var w = e.kind === "artist" ? 0.6 + (e.weight / 12) * 3.4 : 0.5 + e.weight * 1.6;
      var ln = el("line", {
        x1: a.x, y1: a.y, x2: b.x, y2: b.y,
        "class": "nw-edge" + (e.kind === "co-credit" ? " is-cocredit" : ""),
        "stroke-width": Math.min(w, 5).toFixed(1),
        "aria-hidden": "true"
      }, gEdges);
      return { e: e, ln: ln };
    });

    function redrawEdges() {
      edgeEls.forEach(function (rec) {
        var a = byId[rec.e.a], b = byId[rec.e.b];
        rec.ln.setAttribute("x1", a.x); rec.ln.setAttribute("y1", a.y);
        rec.ln.setAttribute("x2", b.x); rec.ln.setAttribute("y2", b.y);
      });
    }

    /* ---------------- nodes ---------------- */
    nodes.forEach(function (n) {
      var g = el("g", {
        "class": "nw-node is-" + n.kind,
        tabindex: "0", role: "button", "aria-pressed": "false",
        "data-id": n.id,
        "aria-label": nodeAria(n)
      }, gNodes);

      var shape;
      if (n.kind === "producer") {
        // producers: squares — a different shape and color, by rule
        shape = el("rect", {
          x: (n.x - n.r).toFixed(1), y: (n.y - n.r).toFixed(1),
          width: (n.r * 2).toFixed(1), height: (n.r * 2).toFixed(1),
          rx: "4", "class": "nw-shape"
        }, g);
      } else {
        shape = el("circle", {
          cx: n.x, cy: n.y, r: n.r, "class": "nw-shape"
        }, g);
      }

      var t = el("text", {
        x: n.x, y: (n.y + n.r + 16).toFixed(1),
        "class": "nw-label", "text-anchor": "middle"
      }, g);
      t.textContent = n.name;

      var c = null;
      if (n.kind === "artist") {
        var at = el("text", {
          x: n.x, y: (n.y + 7).toFixed(1),
          "class": "nw-artist-label", "text-anchor": "middle", "aria-hidden": "true"
        }, g);
        at.textContent = "A✦";
      } else {
        c = el("text", {
          x: n.x, y: (n.y + 4).toFixed(1),
          "class": "nw-count", "text-anchor": "middle", "aria-hidden": "true"
        }, g);
        c.textContent = "×" + n.track_count;
      }

      var rec = { n: n, g: g, shape: shape, label: t, countEl: c };
      recById[n.id] = rec;
      if (n.kind !== "artist") nodeEls.push(rec);

      g.addEventListener("click", function () { selectNode(n.id); });
      g.addEventListener("keydown", function (ev) { nodeKey(ev, rec); });

      /* drag — static layout; dragging only moves what you grab */
      g.addEventListener("pointerdown", function (ev) {
        var pt = svgPoint(ev);
        var dx = n.x - pt.x, dy = n.y - pt.y;
        g.setPointerCapture(ev.pointerId);
        function move(ev2) {
          var p = svgPoint(ev2);
          n.x = Math.max(n.r, Math.min(W - n.r, p.x + dx));
          n.y = Math.max(n.r, Math.min(H - n.r, p.y + dy));
          moveNode(rec);
          redrawEdges();
        }
        function up() {
          g.removeEventListener("pointermove", move);
          g.removeEventListener("pointerup", up);
        }
        g.addEventListener("pointermove", move);
        g.addEventListener("pointerup", up);
      });
    });

    var artistRec = recById.aster;

    function moveNode(rec) {
      var n = rec.n;
      if (rec.shape.tagName === "rect") {
        rec.shape.setAttribute("x", (n.x - n.r).toFixed(1));
        rec.shape.setAttribute("y", (n.y - n.r).toFixed(1));
      } else {
        rec.shape.setAttribute("cx", n.x); rec.shape.setAttribute("cy", n.y);
      }
      rec.label.setAttribute("x", n.x);
      rec.label.setAttribute("y", (n.y + n.r + 16).toFixed(1));
      if (rec.countEl) {
        rec.countEl.setAttribute("x", n.x);
        rec.countEl.setAttribute("y", (n.y + 4).toFixed(1));
      }
    }

    function svgPoint(ev) {
      var pt = svg.createSVGPoint();
      pt.x = ev.clientX; pt.y = ev.clientY;
      return pt.matrixTransform(svg.getScreenCTM().inverse());
    }

    function nodeAria(n) {
      if (n.kind === "artist") return "Aster da Master — activate to reset the selection";
      var kindWord = n.kind === "producer" ? "producer, " : "";
      return n.name + ", " + kindWord + n.track_count + " shared transmissions. Activate to list them.";
    }

    function nodeKey(ev, rec) {
      var k = ev.key;
      if (k === "Enter" || k === " ") { ev.preventDefault(); selectNode(rec.n.id); }
      else if (k === "ArrowRight" || k === "ArrowDown") { ev.preventDefault(); focusStep(rec, 1); }
      else if (k === "ArrowLeft" || k === "ArrowUp") { ev.preventDefault(); focusStep(rec, -1); }
      else if (k === "Escape") { ev.preventDefault(); clearAll(); }
    }

    function focusStep(rec, dir) {
      var order = nodeEls.concat([artistRec]);
      var i = order.indexOf(rec);
      var nx = order[(i + dir + order.length) % order.length];
      nx.g.focus();
    }

    /* ---------------- selection + side panel ---------------- */
    function linkedWith(id) {
      return edges.filter(function (e) {
        return e.kind === "co-credit" && (e.a === id || e.b === id);
      }).map(function (e) {
        var other = byId[e.a === id ? e.b : e.a];
        return { id: other.id, name: other.name, weight: e.weight, tracks: e.shared_tracks || [] };
      });
    }

    function selectNode(id) {
      nodeEls.forEach(function (r) {
        var on = r.n.id === id;
        r.g.classList.toggle("is-selected", on);
        r.g.setAttribute("aria-pressed", on ? "true" : "false");
      });
      var artistOn = id === "aster";
      artistRec.g.classList.toggle("is-selected", artistOn);
      artistRec.g.setAttribute("aria-pressed", artistOn ? "true" : "false");

      var n = byId[id];
      if (artistOn) { resetPanel(); return; }

      var links = linkedWith(id);
      var linkHtml = links.length ? "<h4>Also linked in the vault</h4><ul class=\"nw-links\">" +
        links.map(function (l) {
          return "<li><button type=\"button\" class=\"nw-link\" data-id=\"" + esc(l.id) + "\">" +
            esc(l.name) + " <span class=\"top-n\">×" + l.weight + "</span></button>" +
            "<br><span class=\"chart-sub\">" + l.tracks.map(esc).join("; ") + "</span></li>";
        }).join("") + "</ul>" : "";

      panel.innerHTML =
        "<h3>" + esc(n.name) + "</h3>" +
        "<p class=\"chart-sub\">" + (n.kind === "producer" ? "Producer (scene figure)" : "Title-credited collaborator") +
        " · " + n.track_count + " shared transmission" + (n.track_count === 1 ? "" : "s") +
        " · " + esc(n.first_date || "—") + " → " + esc(n.last_date || "—") + "</p>" +
        "<p><a class=\"btn btn-sm\" href=\"" + esc(n.page) + "\">Full page →</a></p>" +
        "<h4>Shared transmissions</h4>" +
        "<ol class=\"top-list\">" + n.tracks.map(function (t) {
          return "<li><span>" + esc(t.title) + "</span><span class=\"top-n\">" + esc(metaLine(t)) + "</span></li>";
        }).join("") + "</ol>" + linkHtml;

      panel.querySelectorAll(".nw-link").forEach(function (b) {
        b.addEventListener("click", function () {
          var nid = b.getAttribute("data-id");
          selectNode(nid);
          recById[nid].g.focus();
        });
      });
    }

    function resetPanel() {
      panel.innerHTML = "<p class=\"chart-sub\">Select a node to see their transmissions.</p>";
    }

    artistRec.g.addEventListener("click", clearAll);
    artistRec.g.addEventListener("keydown", function (ev) {
      if (ev.key === "Enter" || ev.key === " ") { ev.preventDefault(); clearAll(); }
      else nodeKey(ev, artistRec);
    });

    /* ---------------- controls: era, producers, search ---------------- */
    var eraSlider = document.getElementById("nw-era");
    var eraLabel = document.getElementById("nw-era-label");
    var eraAll = document.getElementById("nw-era-all");
    var prodToggle = document.getElementById("nw-producers");
    var search = document.getElementById("nw-search");

    function nodeVisible(n) {
      return n.kind !== "producer" || prodToggle.checked;
    }

    function applyFilters() {
      var year = eraAll.checked ? null : parseInt(eraSlider.value, 10);
      eraLabel.textContent = year === null ? "All years" : String(year);
      eraSlider.disabled = year === null;
      var q = search.value.trim().toLowerCase();
      var showProd = prodToggle.checked;

      nodes.forEach(function (n) {
        if (n.kind === "artist") return;
        var g = recById[n.id].g;
        var inYear = year === null || n.years.indexOf(year) !== -1;
        var hit = !q || n.name.toLowerCase().indexOf(q) !== -1;
        var hidden = (n.kind === "producer" && !showProd);
        g.classList.toggle("is-dim", !hidden && !(inYear && hit));
        g.classList.toggle("is-hidden", hidden);
        g.setAttribute("tabindex", hidden ? "-1" : "0");
      });

      edgeEls.forEach(function (rec) {
        var a = byId[rec.e.a], b = byId[rec.e.b];
        var endHidden = function (n) { return n.kind !== "artist" && !nodeVisible(n); };
        var hidden = endHidden(a) || endHidden(b);
        var lit = !hidden && (year === null ||
          [a, b].some(function (n) { return n.kind === "artist" || n.years.indexOf(year) !== -1; }));
        rec.ln.classList.toggle("is-dim", !lit && !hidden);
        rec.ln.classList.toggle("is-hidden", hidden);
      });

      renderTable(year, q, showProd);
    }

    eraSlider.addEventListener("input", function () { eraAll.checked = false; applyFilters(); });
    eraAll.addEventListener("change", applyFilters);
    prodToggle.addEventListener("change", applyFilters);
    search.addEventListener("input", applyFilters);
    search.addEventListener("keydown", function (ev) {
      if (ev.key === "Escape") { search.value = ""; applyFilters(); }
    });

    function clearAll() {
      search.value = "";
      eraAll.checked = true;
      prodToggle.checked = true;
      eraSlider.value = "2018";
      resetPanel();
      applyFilters();
    }

    /* ---------------- table: the accessible core ---------------- */
    function renderTable(year, q, showProd) {
      var rows = nodes.filter(function (n) { return n.kind !== "artist"; })
        .filter(function (n) { return showProd || n.kind !== "producer"; })
        .filter(function (n) { return year === null || n.years.indexOf(year) !== -1; })
        .filter(function (n) { return !q || n.name.toLowerCase().indexOf(q) !== -1; })
        .sort(function (a, b) { return b.track_count - a.track_count || (a.name < b.name ? -1 : 1); });

      tableBody.innerHTML = rows.map(function (n) {
        return "<tr><th scope=\"row\"><a href=\"" + esc(n.page) + "\">" + esc(n.name) + "</a></th>" +
          "<td>" + (n.kind === "producer" ? "Producer" : "Collaborator") + "</td>" +
          "<td class=\"num\">" + n.track_count + "</td>" +
          "<td>" + esc(n.first_date || "—") + "</td>" +
          "<td>" + esc(n.last_date || "—") + "</td></tr>";
      }).join("");
      tableWrap.querySelector(".nw-table-note").textContent =
        rows.length + " of " + (nodes.length - 1) + " nodes" +
        (year !== null ? " · active in " + year : "") + (q ? " · matching “" + q + "”" : "");
    }

    /* ---------------- init ---------------- */
    resetPanel();
    applyFilters();
  }).catch(function () {
    panel.innerHTML = "<p class=\"chart-sub\">Could not load the network data.</p>";
    insights.innerHTML = "";
  });
})();
